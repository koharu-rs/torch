"""Writes koharu-torch's C functions, one for each ATen operator in a PyTorch
source tree, as koharu_torch_aten.h and koharu_torch_aten.cpp.

The functions follow libtorch's own C shim, which torchgen generates for
AOTInductor (torchgen/gen_aoti_c_shim.py): a tensor is libtorch's
AtenTensorHandle, an argument takes the same C types, and an error is caught
and kept for libtorch's torch_exception_get_what. They differ where that shim
serves Inductor rather than a general caller:

- Each calls the operator's dispatcher entry, at::_ops::<operator>::call,
  which every operator has, method-only ones included.
- A tensor reaches the operator as it is. The AOTInductor shim clones a
  conjugate or negative view first, because its backend kernels skip the
  dispatcher, which resolves those views itself; a clone would lose an
  in-place write.
- A Scalar crosses as KoharuTorchScalar, which keeps its type. The
  AOTInductor shim's double turns an integer into a float, which changes
  type promotion.
- A Tensor[] result crosses as an array of handles.
"""

import argparse
import sys
from pathlib import Path

HEADER = """\
// Generated by generate.py from PyTorch's native_functions.yaml. Do not edit.

#pragma once

#include "koharu_torch.h"

#ifdef __cplusplus
extern "C" {{
#endif

{declarations}

#ifdef __cplusplus
}} // extern "C"
#endif
"""

SOURCE = """\
// Generated by generate.py from PyTorch's native_functions.yaml. Do not edit.

#include "koharu_torch_aten.h"
#include "convert.h"

#include <ATen/Operators.h>

using namespace torch::aot_inductor;

{definitions}
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("pytorch", type=Path, help="the PyTorch source tree")
    parser.add_argument("out", type=Path, help="the folder to write into")
    args = parser.parse_args()

    sys.path.insert(0, str(args.pytorch))
    from torchgen.gen import parse_native_yaml
    from torchgen.model import BaseTy, BaseType, ListType, OptionalType

    # Each base type's C type, ATen type, and conversion of the C argument `{}`.
    base = {
        BaseTy.Tensor: ("AtenTensorHandle", "at::Tensor", "*tensor_handle_to_tensor_pointer({})"),
        BaseTy.bool: ("int32_t", "bool", "{}"),
        BaseTy.int: ("int64_t", "int64_t", "{}"),
        BaseTy.SymInt: ("int64_t", "c10::SymInt", "{}"),
        BaseTy.float: ("double", "double", "{}"),
        BaseTy.str: ("const char*", "std::string_view", "{}"),
        BaseTy.Scalar: ("KoharuTorchScalar", "c10::Scalar", "koharu_torch_scalar({})"),
        BaseTy.ScalarType: ("int32_t", "c10::ScalarType", "static_cast<c10::ScalarType>({})"),
        BaseTy.Layout: ("int32_t", "c10::Layout", "static_cast<c10::Layout>({})"),
        BaseTy.MemoryFormat: ("int32_t", "c10::MemoryFormat", "static_cast<c10::MemoryFormat>({})"),
        BaseTy.QScheme: ("int32_t", "c10::QScheme", "static_cast<c10::QScheme>({})"),
        BaseTy.DeviceIndex: ("int32_t", "c10::DeviceIndex", "static_cast<c10::DeviceIndex>({})"),
        BaseTy.Generator: ("AtenGeneratorHandle", "at::Generator", "*generator_handle_to_generator_pointer({})"),
    }
    # Each result type's C type and assignment of the ATen value `{v}` to `{r}`.
    results = {
        BaseType(BaseTy.Tensor): ("AtenTensorHandle", "*{r} = new_tensor_handle(std::move({v}));"),
        BaseType(BaseTy.bool): ("int32_t", "*{r} = {v};"),
        BaseType(BaseTy.int): ("int64_t", "*{r} = {v};"),
        BaseType(BaseTy.SymInt): ("int64_t", "*{r} = {v}.expect_int();"),
        BaseType(BaseTy.SymBool): ("int32_t", "*{r} = {v}.guard_bool(__FILE__, __LINE__);"),
        BaseType(BaseTy.float): ("double", "*{r} = {v};"),
        BaseType(BaseTy.Scalar): ("KoharuTorchScalar", "*{r} = koharu_torch_from_scalar({v});"),
        BaseType(BaseTy.ScalarType): ("int32_t", "*{r} = static_cast<int32_t>({v});"),
        BaseType(BaseTy.Layout): ("int32_t", "*{r} = static_cast<int32_t>({v});"),
        BaseType(BaseTy.MemoryFormat): ("int32_t", "*{r} = static_cast<int32_t>({v});"),
        BaseType(BaseTy.QScheme): ("int32_t", "*{r} = static_cast<int32_t>({v});"),
    }

    def known(ty):
        if ty not in base:
            raise NotImplementedError(f"{ty}")
        return base[ty]

    def argument(typ, name):
        """The C parameters and the conversion to ATen of an argument."""
        if isinstance(typ, BaseType):
            if typ.name == BaseTy.Device:
                return (
                    [f"int32_t {name}", f"int32_t {name}_index_"],
                    f"c10::Device(static_cast<c10::DeviceType>({name}), static_cast<c10::DeviceIndex>({name}_index_))",
                )
            c, _, expr = known(typ.name)
            return [f"{c} {name}"], expr.format(name)
        if isinstance(typ, OptionalType):
            elem = typ.elem
            if isinstance(elem, BaseType):
                if elem.name == BaseTy.Device:
                    return (
                        [f"int32_t* {name}", f"int32_t {name}_index_"],
                        f"pointer_to_optional_device({name}, {name}_index_)",
                    )
                if elem.name == BaseTy.Scalar:
                    return [f"KoharuTorchScalar* {name}"], f"koharu_torch_scalar({name})"
                c, aten, _ = known(elem.name)
                return [f"{c}* {name}"], f"pointer_to_optional<{aten}>({name})"
            if isinstance(elem, ListType) and isinstance(elem.elem, BaseType):
                c, aten, _ = known(elem.elem.name)
                if elem.elem.name in (BaseTy.Tensor, BaseTy.Scalar, BaseTy.bool):
                    raise NotImplementedError(f"{typ}")
                return (
                    [f"const {c}** {name}", f"int64_t {name}_len_"],
                    f"pointer_to_optional_list<{aten}>({name}, {name}_len_)",
                )
            raise NotImplementedError(f"{typ}")
        if isinstance(typ, ListType):
            elem = typ.elem
            params = lambda c: [f"{c} {name}", f"int64_t {name}_len_"]  # noqa: E731
            if isinstance(elem, OptionalType) and elem.elem == BaseType(BaseTy.Tensor):
                optional = "std::optional<at::Tensor>"
                return (
                    params("const AtenTensorHandle**"),
                    f"c10::List<{optional}>(c10::ArrayRef<{optional}>(pointer_to_list<{optional}>({name}, {name}_len_)))",
                )
            if not isinstance(elem, BaseType) or elem.name == BaseTy.Device:
                raise NotImplementedError(f"{typ}")
            if elem.name == BaseTy.Scalar:
                return params("const KoharuTorchScalar*"), f"koharu_torch_scalars({name}, {name}_len_)"
            if elem.name == BaseTy.bool:
                if typ.size is None:
                    raise NotImplementedError(f"{typ}")
                return params("const int32_t*"), f"pointer_to_list<{typ.size}>({name})"
            c, aten, _ = known(elem.name)
            pointer = "const char* const*" if elem.name == BaseTy.str else f"const {c}*"
            return params(pointer), f"pointer_to_list<{aten}>({name}, {name}_len_)"
        raise NotImplementedError(f"{typ}")

    def result(typ, name, value):
        """The C parameters and the assignment of a result."""
        if isinstance(typ, ListType) and typ.elem == BaseType(BaseTy.Tensor):
            return (
                [f"AtenTensorHandle** {name}", f"int64_t* {name}_len_"],
                f"koharu_torch_tensor_list(std::move({value}), {name}, {name}_len_);",
            )
        if typ not in results:
            raise NotImplementedError(f"{typ}")
        c, assignment = results[typ]
        return [f"{c}* {name}"], assignment.format(r=name, v=value)

    def shim(f):
        schema = f.func
        name = schema.name.unambiguous_name()
        params, exprs = [], []
        for arg in schema.arguments.flat_all:
            arg_params, expr = argument(arg.type, arg.name)
            params += arg_params
            exprs.append(expr)
        # An in-place or out= operator returns its mutated arguments, which the
        # caller holds already.
        returns = [] if schema.name.name.inplace or schema.is_out_fn() else schema.returns
        assignments = []
        for index, ret in enumerate(returns):
            # tmp_result, as torchgen calls it, since some operators take an
            # argument named result.
            value = "tmp_result" if len(returns) == 1 else f"std::get<{index}>(tmp_result)"
            ret_params, assignment = result(ret.type, f"ret{index}", value)
            params += ret_params
            assignments.append(assignment)
        signature = f"AOTITorchError koharu_torch_aten_{name}({', '.join(params) or 'void'})"
        call = f"at::_ops::{name}::call({', '.join(exprs)});"
        body = "\n".join([f"auto tmp_result = {call}" if assignments else call, *assignments])
        definition = (
            f"{signature} {{\n"
            "  AOTI_TORCH_CONVERT_EXCEPTION_TO_ERROR_CODE({\n"
            + "".join(f"    {line}\n" for line in body.splitlines())
            + "  });\n}\n"
        )
        return f"KOHARU_TORCH_API {signature};", definition

    native = args.pytorch / "aten" / "src" / "ATen" / "native"
    functions = parse_native_yaml(
        str(native / "native_functions.yaml"), str(native / "tags.yaml")
    ).native_functions
    declarations, definitions, skipped = [], [], []
    for f in sorted(functions, key=lambda f: f.func.name.unambiguous_name()):
        try:
            declaration, definition = shim(f)
        except NotImplementedError as error:
            skipped.append(f"//   {f.func.name}: {error}")
            continue
        declarations.append(declaration)
        definitions.append(definition)

    if skipped:
        declarations.append(
            "// Operators without a C form, and the type that has none:\n" + "\n".join(skipped)
        )
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "koharu_torch_aten.h").write_text(
        HEADER.format(declarations="\n\n".join(declarations)), newline="\n"
    )
    (args.out / "koharu_torch_aten.cpp").write_text(
        SOURCE.format(definitions="\n".join(definitions)), newline="\n"
    )
    print(f"{len(definitions)} operators, {len(skipped)} without a C form")


if __name__ == "__main__":
    main()
